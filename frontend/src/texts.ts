/** Russian plural: 1 код, 2 кода, 5 кодов. */
export function plural(n: number, one: string, few: string, many: string) {
  const last = n % 10
  const tail = n % 100
  if (last === 1 && tail !== 11) return one
  if (last >= 2 && last <= 4 && (tail < 12 || tail > 14)) return few
  return many
}

/** The first letter in capitals: a state said in a sentence, then as a label. */
export function capital(text: string) {
  return text.charAt(0).toUpperCase() + text.slice(1)
}

