/** The dotted map of Russia from the logo of the EIS, drawn as one path of small squares. */
const MAP = [
  '................................##...',
  '..............................####...',
  '.............................#######.',
  '................##...........#######.',
  '...................##....#...######.#',
  '................##..#....#.#######...',
  '..........##..###..####.#.#########..',
  '........#####.#....#################.',
  '....#.###############################',
  '......##########################....#',
  '......#########################......',
  '.....##########################......',
  '.##############################..#...',
  '.....##############################..',
  '###.###############################..',
  '.#.#####..##################..####...',
  '....###....#...#############....##...',
  '.....#...........###########.....#...',
  '.....#............####...............',
]

const PITCH = 4
const DOT = 3

const SHAPE = MAP.flatMap((row, y) =>
  [...row].flatMap((cell, x) => (cell === '#' ? [`M${x * PITCH} ${y * PITCH}h${DOT}v${DOT}h-${DOT}z`] : [])),
).join('')

export function EisMark({ height = 36 }: { height?: number }) {
  const width = MAP[0].length * PITCH
  const total = MAP.length * PITCH
  return (
    <svg
      className="eis-mark"
      width={(height * width) / total}
      height={height}
      viewBox={`0 0 ${width} ${total}`}
      aria-hidden="true"
    >
      <path d={SHAPE} fill="currentColor" />
    </svg>
  )
}
